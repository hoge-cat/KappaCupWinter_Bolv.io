#include "stdafx.h"
#include "TankWeapon.h"


namespace
{
    // ========================================================
    // Triple Shotの左右砲身角度
    //
    // 送ってもらった本家画像に近い形になるよう
    // Bolv.ioでは35度で実装。
    //
    // 本家内部の正確な角度値として断定する値ではなく、
    // 見た目と挙動を近づけるための調整値。
    // ========================================================

    const float TRIPLE_SHOT_SIDE_ANGLE =
        30.0f;


    // ========================================================
    // 左右砲身の発射位置
    //
    // 砲身自体は角度が付いているため
    // 少しだけ左右へ分ける。
    // ========================================================

    const float TRIPLE_SHOT_SIDE_OFFSET =
        6.0f;
}


// ============================================================
// FireTripleShot
// ============================================================

void TankWeapon::FireTripleShot(
    const Vector3& playerPosition,
    const Vector3& aimDirection
)
{
    // ========================================================
    // 中央
    // ========================================================

    Fire(
        playerPosition,
        aimDirection,
        0.0f,
        0.0f
    );


    // ========================================================
    // 左
    // ========================================================

    Fire(
        playerPosition,
        aimDirection,
        -TRIPLE_SHOT_SIDE_OFFSET,
        -TRIPLE_SHOT_SIDE_ANGLE
    );


    // ========================================================
    // 右
    // ========================================================

    Fire(
        playerPosition,
        aimDirection,
        TRIPLE_SHOT_SIDE_OFFSET,
        TRIPLE_SHOT_SIDE_ANGLE
    );
}


// ============================================================
// GetTripleShotReloadMultiplier
// ============================================================

float TankWeapon::GetTripleShotReloadMultiplier() const
{
    // ========================================================
    // まずはBasic基準の発射間隔を使用。
    //
    // 3方向へ同時に射撃することで
    // Triple Shotらしい火力と反動感を再現する。
    //
    // 後で実際のプレイ感を確認して
    // 本家にさらに近づける場合はここだけ調整可能。
    // ========================================================

    return 1.0f;
}