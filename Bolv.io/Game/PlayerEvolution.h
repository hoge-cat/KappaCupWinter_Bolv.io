#pragma once


// ============================================================
// Playerの進化状態を管理する。
//
// 「現在のLv」と「現在のTankClass」から
// 今選択可能な進化先をすべて計算する。
//
// これにより、進化を保留してLvを上げても
// 過去の進化候補が消えない。
// ============================================================

class PlayerEvolution
{
public:

    // ========================================================
    // 進化段階
    // ========================================================

    enum EvolutionStage
    {
        None,

        Level15,
        Level30,
        Level45
    };


    // ========================================================
    // Tank Class
    // ========================================================

    enum TankClass
    {
        // ========================================
        // 初期
        // ========================================

        Basic,


        // ========================================
        // Lv15
        // ========================================

        Twin,

        Sniper,

        MachineGun,

        FlankGuard,


        // ========================================
        // Twin系 Lv30
        // ========================================

        TripleShot,

        QuadTank,

        TwinFlank,


        // ========================================
        // Sniper系 Lv30
        // ========================================

        Assassin,

        Hunter,

        Trapper,


        // ========================================
        // 特殊進化
        // ========================================

        Smasher,



        // ========================================
        // Lv45
        // ========================================

        Sprayer,


        // ========================================
        // Machine Gun系 Lv30
        // ========================================

        Destroyer

    };


public:

    // ========================================================
    // 更新
    // ========================================================

    void Update(
        int currentLevel
    );


    // ========================================================
    // 現在1つ以上進化候補があるか
    // ========================================================

    bool HasAvailableEvolution() const;


    // ========================================================
    // 現在選択可能な進化先の数
    // ========================================================

    int GetAvailableEvolutionCount() const;


    // ========================================================
    // 現在選択可能な進化先を取得
    // ========================================================

    TankClass GetAvailableEvolution(
        int index
    ) const;


    // ========================================================
    // 指定したTankClassへ進化可能か
    // ========================================================

    bool CanEvolveTo(
        TankClass tankClass
    ) const;


    // ========================================================
    // 進化
    // ========================================================

    bool EvolveTo(
        TankClass tankClass
    );


    // ========================================================
    // 現在TankClass
    // ========================================================

    TankClass GetCurrentClass() const
    {
        return m_currentClass;
    }


    // ========================================================
    // 強制TankClass変更
    // ========================================================

    void SetCurrentClass(
        TankClass tankClass
    )
    {
        m_currentClass =
            tankClass;


        m_evolutionSkipped =
            false;
    }


    // ========================================================
    // 現在Lv
    // ========================================================

    int GetCurrentLevel() const
    {
        return m_currentLevel;
    }


    // ========================================================
    // 進化UIを一時的に閉じる
    // ========================================================

    void SkipEvolution()
    {
        m_evolutionSkipped =
            true;
    }


    // ========================================================
    // 旧コード互換
    // ========================================================

    EvolutionStage GetAvailableStage() const;


private:

    // ========================================================
    // 現在Class
    // ========================================================

    TankClass m_currentClass =
        Basic;


    // ========================================================
    // 現在Lv
    // ========================================================

    int m_currentLevel =
        1;


    // ========================================================
    // 前回Lv
    // ========================================================

    int m_previousLevel =
        1;


    // ========================================================
    // 進化UIを閉じているか
    // ========================================================

    bool m_evolutionSkipped =
        false;
};