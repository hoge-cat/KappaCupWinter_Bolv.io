#include "stdafx.h"
#include "TankWeapon.h"


// ============================================================
// Quad Tank
//
// 4本の砲身から
//
// 正面
// 右
// 後方
// 左
//
// の4方向へ同時発射する。
// ============================================================

void TankWeapon::FireQuadTank(
    const Vector3& playerPosition,
    const Vector3& aimDirection
)
{
    // ========================================================
    // 正面
    // ========================================================

    Fire(
        playerPosition,
        aimDirection,
        0.0f,
        0.0f
    );


    // ========================================================
    // 右
    // ========================================================

    Fire(
        playerPosition,
        aimDirection,
        0.0f,
        90.0f
    );


    // ========================================================
    // 後方
    // ========================================================

    Fire(
        playerPosition,
        aimDirection,
        0.0f,
        180.0f
    );


    // ========================================================
    // 左
    // ========================================================

    Fire(
        playerPosition,
        aimDirection,
        0.0f,
        -90.0f
    );
}