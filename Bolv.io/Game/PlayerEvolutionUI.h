    // ========================================================
    // マウスが選択肢上にあるか
    // ========================================================

    bool IsMouseOverOption(
        int optionIndex
    ) const;


private:

    // ========================================================
    // Player
    // ========================================================

    Player* m_player =
        nullptr;


    // ========================================================
    // Title
    // ========================================================

    FontRender m_titleFontRender;


    // ========================================================
    // Options
    // ========================================================

