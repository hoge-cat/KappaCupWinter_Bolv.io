private:

    // ========================================================
    // 表示可能な最大候補数
    //
    // 今後進化先が増えても対応しやすいよう
    // 少し余裕を持たせる。
    // ========================================================

    static const int MAX_OPTION_COUNT =
        8;


    // ========================================================
