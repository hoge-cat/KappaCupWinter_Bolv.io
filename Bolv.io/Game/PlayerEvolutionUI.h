    // 現在の候補をUIへ反映
    // ========================================================

    void UpdateOptionTexts();


    // ========================================================
    // Hover色更新
    // ========================================================

    void UpdateHoverColors();


    // ========================================================
    // クリック処理
    // ========================================================

