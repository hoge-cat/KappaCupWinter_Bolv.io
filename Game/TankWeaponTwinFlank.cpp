#include "stdafx.h"
#include "TankWeapon.h"


namespace
{
    // ========================================================
    // Twin / Twin Flankの砲身左右位置
    //
    // 現在のTwinと同程度の間隔。
    // ========================================================

    const float TWIN_FLANK_BARREL_OFFSET =
        11.0f;
}


// ============================================================
// FireTwinFlank
//
// 本家Twin Flank:
//
// 前にTwin
// 後ろにもTwin
//
// 前後は同時に発射し、
// それぞれ左右の砲身を交互に使用する。
// ============================================================

void TankWeapon::FireTwinFlank(
    const Vector3& playerPosition,
    const Vector3& aimDirection
)
{
    // ========================================================
    // 左側砲身のターン
    // ========================================================

    if (m_twinFlankFireLeft)
    {
        // ========================================
        // 前方左
        // ========================================

        Fire(
            playerPosition,
            aimDirection,
            -TWIN_FLANK_BARREL_OFFSET,
            0.0f
        );


        // ========================================
        // 後方左
        //
        // Fire()では180度回転後にright方向も
        // 反転するため、同じワールド側へ出すには
        // sideOffsetの符号を逆にする。
        // ========================================

        Fire(
            playerPosition,
            aimDirection,
            TWIN_FLANK_BARREL_OFFSET,
            180.0f
        );
    }


    // ========================================================
    // 右側砲身のターン
    // ========================================================

    else
    {
        // ========================================
        // 前方右
        // ========================================

        Fire(
            playerPosition,
            aimDirection,
            TWIN_FLANK_BARREL_OFFSET,
            0.0f
        );


        // ========================================
        // 後方右
        // ========================================

        Fire(
            playerPosition,
            aimDirection,
            -TWIN_FLANK_BARREL_OFFSET,
            180.0f
        );
    }


    // ========================================================
    // 次は反対側
    // ========================================================

    m_twinFlankFireLeft =
        !m_twinFlankFireLeft;
}


// ============================================================
// Reload
// ============================================================

float TankWeapon::GetTwinFlankReloadMultiplier() const
{
    // ============================================
    // Twinと同じ発射周期を使用する。
    //
    // 前後に1発ずつ出るため、
    // 総発射数はTwin Flankらしく増える。
    // ============================================

    return
        GetTwinReloadMultiplier();
}


// ============================================================
// Bullet Damage
// ============================================================

float TankWeapon::GetTwinFlankBulletDamageMultiplier() const
{
    // ============================================
    // Diep.io:
    //
    // Basic
    // 7 + 3 * Level
    //
    // Twin Flank
    // 4.2 + 1.8 * Level
    //
    // つまりBasicの60%。
    // ============================================

    return
        0.60f;
}


// ============================================================
// Bullet Penetration
// ============================================================

float TankWeapon::GetTwinFlankBulletPenetrationMultiplier() const
{
    // ============================================
    // Diep.io:
    //
    // Basic
    // 2.0 + 1.5 * Level
    //
    // Twin Flank
    // 1.8 + 1.35 * Level
    //
    // つまりBasicの90%。
    // ============================================

    return
        0.90f;
}